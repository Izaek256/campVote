"use client";

import Link from "next/link";
import { use, useEffect, useState } from "react";
import { Icon } from "@/components/icon";
import { RequireAuth } from "@/components/require-auth";
import { SiteHeader } from "@/components/site-header";
import { Countdown } from "@/components/countdown";
import { LoadError } from "@/components/load-error";
import { StatusChip } from "@/components/status-chip";
import { useToast } from "@/components/toast";
import { ApiError, candidates, documents, elections, fileUrl } from "@/lib/api";
import { categoryLabel, formatEAT, formatNumber, statusLabel } from "@/lib/format";
import type { BallotPosition, Election, EligibilityDecision } from "@/lib/types";

const railStates = ["DRAFT", "OPEN", "CLOSED"] as const;

const railLabels: Record<string, string> = {
  DRAFT: "Draft",
  OPEN: "Open",
  CLOSED: "Closed",
};

function LifecycleRail({ status }: { status: Election["status"] }) {
  const current = Math.max(0, railStates.indexOf(status as (typeof railStates)[number]));
  return (
    <div className="rail" role="group" aria-label={`Election state: ${statusLabel(status)}`}>
      {railStates.map((state, index) => (
        <div
          key={state}
          className={`ls${index < current ? " done" : ""}${index === current ? " cur" : ""}`}
        >
          {railLabels[state]}
        </div>
      ))}
    </div>
  );
}

function ElectionView({ id }: { id: string }) {
  const toast = useToast();
  const [election, setElection] = useState<Election | null>(null);
  const [eligibility, setEligibility] = useState<EligibilityDecision | null>(null);
  const [candidatePositions, setCandidatePositions] = useState<BallotPosition[] | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [downloadingInfo, setDownloadingInfo] = useState(false);

  useEffect(() => {
    let active = true;
    elections
      .list()
      .then((list) => {
        const found = list.find((item) => item.id === id);
        if (!found) throw new ApiError("This election is not available to you.", 404);
        if (active) setElection(found);
      })
      .catch((err) => {
        if (!active) return;
        const message = err instanceof ApiError ? err.message : "Election could not be loaded.";
        setLoadError(message);
        toast.error(message);
      });
    elections
      .eligibility(id)
      .then((decision) => {
        if (active) setEligibility(decision);
      })
      .catch(() => {
        if (active)
          setEligibility({
            eligible: false,
            reason: "Eligibility could not be checked.",
          });
      });
    // The approved candidates and their manifestos, so they can be read before
    // voting opens. A non-eligible viewer is refused; show nothing instead.
    candidates
      .forVoters(id)
      .then((data) => {
        if (active) setCandidatePositions(data.positions ?? []);
      })
      .catch(() => {
        if (active) setCandidatePositions([]);
      });
    return () => {
      active = false;
    };
  }, [id, toast]);

  // The public notice for this election, generated by the API.
  async function downloadInfoSheet() {
    setDownloadingInfo(true);
    try {
      await documents.infoPdf(id);
    } catch (err) {
      toast.error(
        err instanceof ApiError ? err.message : "The information sheet could not be downloaded."
      );
    } finally {
      setDownloadingInfo(false);
    }
  }

  if (loadError) {
    return (
      <main className="app-wrap narrow">
        <LoadError
          title="We could not open this election"
          message={loadError}
          backHref="/elections"
          backLabel="Back to elections"
        />
      </main>
    );
  }

  if (!election) {
    return (
      <main className="app-wrap" aria-busy="true" aria-label="Loading election">
        <div className="skel" style={{ height: 28, width: "45%", marginBottom: 16 }} />
        <div className="panel stack">
          <span className="skel" style={{ height: 14 }} />
          <span className="skel" style={{ height: 14, width: "70%" }} />
        </div>
      </main>
    );
  }

  const voted = Boolean(election.my_vote_status?.voted);
  const canVote = Boolean(eligibility?.eligible) && election.accepting_votes && !voted;
  const ended = election.status === "CLOSED" || new Date(election.ends_at).getTime() <= Date.now();
  const applicationsOpen =
    Boolean(eligibility?.eligible) &&
    election.status === "OPEN" &&
    new Date(election.starts_at).getTime() > Date.now();

  return (
    <main className="app-wrap">
      <nav className="crumbs" aria-label="Breadcrumb" style={{ marginBottom: 16 }}>
        <Link href="/elections">Elections</Link>
        <span>/</span>
        <span>{election.title}</span>
      </nav>

      <div className="page-head">
        <div>
          <div className="row" style={{ marginBottom: 8 }}>
            <StatusChip status={election.status} />
            <span className="tag">{categoryLabel(election.category)}</span>
          </div>
          <h1>{election.title}</h1>
          <p>{election.description}</p>
        </div>
        <button
          type="button"
          className="btn"
          disabled={downloadingInfo}
          onClick={downloadInfoSheet}
        >
          <Icon name="file" size="s" />
          {downloadingInfo ? "Preparing…" : "Information sheet"}
        </button>
      </div>

      <div className="split">
        <div className="stack">
          <section className="panel">
            <div className="section-h" style={{ marginTop: 0 }}>
              <h2>Schedule</h2>
              <span className="mono">{election.display_timezone}</span>
            </div>
            <dl className="kv">
              <dt>Voting opens</dt>
              <dd>{formatEAT(election.starts_at)}</dd>
              <dt>Voting closes</dt>
              <dd>{formatEAT(election.ends_at)}</dd>
              <dt>Organising unit</dt>
              <dd>{election.organizing_unit}</dd>
              <dt>Results policy</dt>
              <dd>{election.result_policy.replaceAll("_", " ").toLowerCase()}</dd>
            </dl>
            <p className="hint" style={{ marginTop: 14 }}>
              The server clock decides when voting opens and closes. Your device clock is only for
              display.
            </p>
          </section>

          <section className="panel">
            <div className="section-h" style={{ marginTop: 0 }}>
              <h2>Lifecycle</h2>
            </div>
            <LifecycleRail status={election.status} />
          </section>

          <section className="panel">
            <div className="section-h" style={{ marginTop: 0 }}>
              <h2>Candidates &amp; manifestos</h2>
              {candidatePositions && candidatePositions.length > 0 ? (
                <span className="lbl">
                  {candidatePositions.reduce((total, p) => total + p.candidates.length, 0)} approved
                </span>
              ) : null}
            </div>
            {candidatePositions === null ? (
              <div className="stack" aria-busy="true">
                <span className="skel" style={{ height: 14 }} />
                <span className="skel" style={{ height: 14, width: "70%" }} />
              </div>
            ) : candidatePositions.length === 0 ? (
              <p className="hint">
                No approved candidates are available for you to read yet. Candidates who are
                approved can publish their manifestos here before voting opens.
              </p>
            ) : (
              <div className="stack">
                {candidatePositions.map((position) => (
                  <div key={position.id}>
                    <div className="row-between">
                      <b>{position.title}</b>
                      <span className="hint">
                        {position.candidates.length} candidate
                        {position.candidates.length === 1 ? "" : "s"}
                      </span>
                    </div>
                    <div className="stack" style={{ marginTop: 12 }}>
                      {position.candidates.map((candidate) => (
                        <article
                          key={candidate.id}
                          className="panel stack"
                          style={{ background: "var(--sunken)" }}
                        >
                          <div className="row" style={{ alignItems: "flex-start", gap: 16 }}>
                            {candidate.photo_url ? (
                              // eslint-disable-next-line @next/next/no-img-element
                              <img
                                src={fileUrl(candidate.photo_url)}
                                alt=""
                                width={64}
                                height={64}
                                style={{ objectFit: "cover", border: "1px solid var(--line)" }}
                              />
                            ) : null}
                            <div className="stack" style={{ gap: 4 }}>
                              <b style={{ fontSize: 17 }}>{candidate.full_name}</b>
                              {candidate.slogan ? (
                                <span className="hint">{candidate.slogan}</span>
                              ) : null}
                              {candidate.bio ? <p style={{ margin: 0 }}>{candidate.bio}</p> : null}
                            </div>
                          </div>
                          {candidate.manifesto ? (
                            <p style={{ whiteSpace: "pre-wrap", margin: 0 }}>
                              {candidate.manifesto}
                            </p>
                          ) : null}
                          {candidate.manifesto_url ? (
                            <a
                              className="btn sm"
                              href={fileUrl(candidate.manifesto_url)}
                              target="_blank"
                              rel="noreferrer"
                              style={{ alignSelf: "flex-start" }}
                            >
                              <Icon name="file" size="s" />
                              Read the manifesto document
                            </a>
                          ) : null}
                          {!candidate.manifesto && !candidate.manifesto_url ? (
                            <span className="hint">No manifesto published yet.</span>
                          ) : null}
                        </article>
                      ))}
                    </div>
                  </div>
                ))}
              </div>
            )}
          </section>

          <div className="banner">
            <Icon name="lock" />
            <div>
              <b>Your vote is secret</b>
              Officials and candidates cannot see your choices. The ballot is stored separately from
              the record that you voted.
            </div>
          </div>
        </div>

        <aside className="stack">
          {election.accepting_votes ? (
            <div className="panel stack">
              <span className="lbl">Voting closes in</span>
              <Countdown endsAt={election.ends_at} />
              {eligibility === null ? (
                <span className="hint">Checking your eligibility…</span>
              ) : eligibility.eligible ? (
                <span className="field okm">
                  <Icon name="check" size="s" />
                  You are on the eligibility roster for this election.
                </span>
              ) : (
                <span className="error-text" role="alert">
                  <Icon name="alert" size="s" />
                  {eligibility.reason ?? "You are not eligible for this election."}
                </span>
              )}
              {voted ? (
                <Link className="btn block lg" href={`/elections/${election.id}/status`}>
                  <Icon name="check" />
                  View vote status
                </Link>
              ) : canVote ? (
                <Link className="btn primary block lg" href={`/elections/${election.id}/ballot`}>
                  <Icon name="ballot" />
                  Open ballot
                </Link>
              ) : (
                <button className="btn block lg" type="button" disabled>
                  Ballot unavailable
                </button>
              )}
            </div>
          ) : (
            <div className="panel stack">
              <span className="lbl">Status</span>
              <b style={{ fontSize: 20 }}>{statusLabel(election.status)}</b>
              <span className="hint">
                {ended
                  ? `Voting closed ${formatEAT(election.ends_at)}.`
                  : `Voting opens ${formatEAT(election.starts_at)}.`}
              </span>
              {ended ? (
                <Link className="btn block" href={`/elections/${election.id}/results`}>
                  <Icon name="chart" />
                  View results
                </Link>
              ) : null}
            </div>
          )}

          <div className="panel stack">
            <span className="lbl">Eligibility</span>
            {eligibility?.eligible ? (
              <span className="field okm">
                <Icon name="check" size="s" />
                Roster entry confirmed
              </span>
            ) : (
              <span className="hint">{eligibility?.reason ?? "Not currently eligible."}</span>
            )}
            <span className="hint">
              {formatNumber(election.eligibility_frozen_count)} voters were on the frozen roster
              when voting opened.
            </span>
            {applicationsOpen ? (
              <Link className="btn block" href={`/elections/${election.id}/candidate/apply`}>
                <Icon name="user" />
                Become a candidate
              </Link>
            ) : null}
          </div>
        </aside>
      </div>
    </main>
  );
}

export default function ElectionPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  return (
    <RequireAuth>
      <SiteHeader />
      <ElectionView id={id} />
    </RequireAuth>
  );
}
